/**
 * 一条 socket 的连接阶段 —— 界面读它画网络格与连接详情。
 *
 * 取值的含义是「这条连接走到哪一步」，与这条连接上登记了几条流无关：在已就绪的
 * 连接上开第二条流，屏幕不该闪一下「连接中」。
 *
 * 它是顶层类型而不是嵌套在传输层里：界面要读它，而界面一旦写 `WebSocketConnection.Phase`
 * 就等于持有了传输层 —— 那是另一条判据禁止的。
 *
 * 与组网的 `MeshPhase` 不是同一件事：那一层说隧道通不通，这一层说 socket 连没连上。
 */
enum ConnectionPhase: Equatable {
    /// 没有连接，也没有排定的重试。
    case idle
    /// **在等组网**：本层连不上不是它的错，而是外面还没有可连的地址。
    ///
    /// 与 `.waiting` 的分界是**谁该重试**：`.waiting` 说「等一会儿我自己再来」，
    /// 这里说「别自己来，等组网就绪那一刻有人叫我」。所以它**不排定时器、不累加退避档位**
    /// —— 组网没起来之前，每一次尝试都是必然失败的，把它记成网络失败会让退避一路爬到上限，
    /// 于是组网真就绪时第一发就等 10 秒。
    case awaitingMesh
    /// 正在握手。
    case connecting
    /// 这条连接已经通了：本代收到过至少一条可解析的帧。
    case ready
    /// 等一轮退避后重连；携带毫秒数，界面可以如实显示。
    case waiting(ms: Int)
}
